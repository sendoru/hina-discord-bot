"""Conversation SQL using the runtime Store connection and existing retention policy."""

import json
import sqlite3

from .memory_context import CURRENT_CONTEXT_PROVENANCE, CURRENT_MEMORY_CONTEXT
from .observability import current_turn_id
from .routing import Scope


class ConversationRepository:
    """Standalone methods retain commits; write_* helpers borrow a caller transaction."""

    def __init__(self, db: sqlite3.Connection, history_turns: int = 12):
        self.db = db
        self.history_turns = history_turns

    def user_name(self, scope: Scope) -> str:
        """Return the latest observed human-readable name for this scoped user."""
        for sql in (
            "SELECT name FROM turns WHERE scope=? AND name<>'' ORDER BY id DESC LIMIT 1",
            "SELECT name FROM shared_calls WHERE scope=? AND name<>'' ORDER BY id DESC LIMIT 1",
            "SELECT name FROM shared_summaries WHERE scope=? AND name<>'' LIMIT 1",
            "SELECT name FROM conversation_identity_names WHERE scope=? LIMIT 1",
        ):
            row = self.db.execute(sql, (scope.conversation,)).fetchone()
            if row is not None and str(row[0] or "").strip():
                return str(row[0])[:100]
        return ""

    def latest_conversation_reset_cutoff(self) -> int:
        """Bound automatic Discord history backfill after an offline reset."""
        if self.db.execute(
            """SELECT 1 FROM sqlite_master WHERE type='table'
               AND name='conversation_reset_epochs'"""
        ).fetchone() is None:
            return 0
        row = self.db.execute(
            "SELECT cutoff_message_id FROM conversation_reset_epochs "
            "ORDER BY id DESC LIMIT 1"
        ).fetchone()
        return int(row[0]) if row is not None else 0

    def latest_turn_at(self, user_id: int | str) -> str | None:
        """When this user last completed a turn with Hina in any space (session gaps)."""
        row = self.db.execute(
            "SELECT MAX(created_at) FROM turns WHERE user_id=?", (str(user_id),)
        ).fetchone()
        return str(row[0]) if row is not None and row[0] else None

    def history(self, scope: Scope):
        return list(reversed(self.db.execute(
            "SELECT * FROM turns WHERE scope=? ORDER BY id DESC LIMIT ?",
            (scope.conversation, self.history_turns)).fetchall()))

    def chat_history_records(self, scope: Scope, message_ids):
        """Read bounded source records; callers must verify live access before disclosure.

        This is deliberately separate from automatic history and does not restore archived turns.
        Only successful exchanges are eligible. Debug prompts and internal metadata never leave
        this repository; delivery IDs and the history-derived flag are explicitly projected.
        """
        ids = list(dict.fromkeys(str(value) for value in message_ids))
        if len(ids) > 100 or any(
            not value.isascii() or not value.isdecimal() or not 0 < int(value) < 2**63
            for value in ids
        ):
            raise ValueError("Expected at most 100 Discord message IDs")
        if not ids:
            return []
        placeholders = ','.join('?' for _ in ids)
        # Scope strings are generated by Scope, never by the model. Guild lookups may include
        # different authors in this exact channel; DMs remain restricted to their owner.
        condition = "realm=? AND scope=(? || user_id)"
        params = (scope.realm, scope.channel + ':user:', *ids)
        fields = "user_id,name,message_id,content,reply,created_at,context_provenance"
        sources = [("sqlite", "turns", "")]
        if self.db.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' "
            "AND name='conversation_debug_archive'"
        ).fetchone():
            sources.append(("archive", "conversation_debug_archive", " AND record_type='turn'"))
        result = []
        for source, table, extra in sources:
            rows = self.db.execute(
                f"SELECT {fields} FROM {table} WHERE {condition} "
                f"AND message_id IN ({placeholders}){extra} LIMIT 100", params,
            ).fetchall()
            for row in rows:
                if scope.guild_id is None and row['user_id'] != str(scope.user_id):
                    continue
                try:
                    provenance = json.loads(row['context_provenance'] or '{}')
                except (ValueError, TypeError):
                    provenance = {}
                if not isinstance(provenance, dict):
                    provenance = {}
                delivery = provenance.get('assistant_message_ids', [])
                result.append({
                    key: row[key] for key in (
                        'user_id', 'name', 'message_id', 'content', 'reply', 'created_at',
                    )
                } | {
                    'source': source,
                    'history_derived': bool(provenance.get('history_lookup')),
                    'assistant_message_ids': [
                        str(value) for value in delivery[:4]
                        if isinstance(value, str) and value.isascii() and value.isdecimal()
                    ] if isinstance(delivery, list) else [],
                })
        return result

    def seen(self, message_id: int):
        return self.db.execute("SELECT 1 FROM turns WHERE message_id=?",
                               (str(message_id),)).fetchone() is not None

    def chat_history_reply_metadata(self, scope: Scope, message_ids):
        """Recover content-free provenance for delivered history-derived assistant messages."""
        ids = list(dict.fromkeys(str(value) for value in message_ids))
        if len(ids) > 100:
            raise ValueError('Expected at most 100 message IDs')
        if not ids:
            return {}
        placeholders = ','.join('?' for _ in ids)
        rows = self.db.execute(
            "SELECT j.value AS reply_id,t.context_provenance FROM turns t, "
            "json_each(CASE WHEN json_valid(t.context_provenance) "
            "THEN t.context_provenance ELSE '{}' END,'$.assistant_message_ids') j "
            "WHERE t.realm=? AND t.scope=(? || t.user_id) "
            f"AND j.value IN ({placeholders})", (scope.realm, scope.channel + ':user:', *ids),
        ).fetchall()
        result = {}
        for row in rows:
            provenance = json.loads(row['context_provenance'])
            history = provenance.get('history_lookup')
            if isinstance(history, dict) and history:
                result[str(row['reply_id'])] = history
        return result

    def add(
        self, scope, message_id, content, reply, *, name="", memory_context=None,
        context_provenance=None,
    ):
        values = self.turn_values(
            scope, message_id, content, reply, name=name, memory_context=memory_context,
            context_provenance=context_provenance,
        )
        with self.db:
            self.write_turn(scope, values)

    def turn_values(
        self,
        scope: Scope,
        message_id: int,
        content: str,
        reply: str,
        *,
        name: str = "",
        memory_context=None,
        context_provenance=None,
    ):
        # Legacy code chained this bit through the personal summary to prevent a mixed
        # summary from becoming public. Structured extraction tracks provenance per turn,
        # so the retained column can now represent capture visibility directly.
        exportable = scope.public_at_capture
        if memory_context is None:
            memory_context = CURRENT_MEMORY_CONTEXT.get()
            CURRENT_MEMORY_CONTEXT.set(())
        encoded_context = (
            json.dumps(list(memory_context), ensure_ascii=False, separators=(",", ":"))
            if memory_context
            else ""
        )
        if context_provenance is None:
            context_provenance = CURRENT_CONTEXT_PROVENANCE.get()
            CURRENT_CONTEXT_PROVENANCE.set(None)
        encoded_provenance = (
            json.dumps(context_provenance, ensure_ascii=False, separators=(",", ":"))
            if context_provenance
            else ""
        )
        return (
            scope.conversation, scope.realm, str(scope.user_id), str(name or "")[:100],
            str(message_id), content, reply, int(exportable), current_turn_id(),
            encoded_context, encoded_provenance,
        )

    def write_turn(self, scope, values):
        """Insert and prune on the caller's transaction, using already encoded values."""
        self.db.execute(
            "INSERT INTO turns(scope,realm,user_id,name,message_id,content,reply,exportable,"
            "turn_id,memory_context,context_provenance) VALUES (?,?,?,?,?,?,?,?,?,?,?)", values,
        )
        # Keep the existing retention policy; its separation belongs to #399.
        self.db.execute("DELETE FROM turns WHERE scope=? AND id NOT IN "
                        "(SELECT id FROM turns WHERE scope=? ORDER BY id DESC LIMIT ?)",
                        (scope.conversation, scope.conversation, self.history_turns))

    def add_failed_turn(
        self,
        scope: Scope,
        message_id: int,
        content: str,
        *,
        name: str = "",
        reply: str = "",
        status: str,
        stage: str,
        reply_delivered: bool,
        error_type: str = "",
        error_fingerprint: str = "",
    ):
        """Persist a failed exchange for observability without feeding memory pipelines."""
        with self.db:
            self.db.execute(
                """INSERT INTO failed_turns(
                       scope,realm,user_id,name,message_id,content,reply,turn_id,
                       status,stage,reply_delivered,error_type,error_fingerprint
                   ) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)""",
                (
                    scope.conversation,
                    scope.realm,
                    str(scope.user_id),
                    str(name or "")[:100],
                    str(message_id),
                    content,
                    reply,
                    current_turn_id(),
                    str(status),
                    str(stage),
                    int(bool(reply_delivered)),
                    str(error_type or ""),
                    str(error_fingerprint or ""),
                ),
            )
            self.db.execute(
                """DELETE FROM failed_turns
                   WHERE scope=? AND id NOT IN (
                       SELECT id FROM failed_turns
                       WHERE scope=? ORDER BY id DESC LIMIT ?
                   )""",
                (scope.conversation, scope.conversation, self.history_turns),
            )

    def write_shared_call(self, scope, message_id, name, content):
        if scope.guild_id is None or not scope.public_at_capture:
            return
        self.db.execute("INSERT OR IGNORE INTO shared_calls "
                        "(scope,realm,user_id,message_id,name,content) VALUES (?,?,?,?,?,?)",
                        (scope.conversation, scope.realm, str(scope.user_id), str(message_id),
                         name[:100], content))
        self.db.execute("DELETE FROM shared_calls WHERE scope=? AND id NOT IN "
                        "(SELECT id FROM shared_calls WHERE scope=? ORDER BY id DESC LIMIT ?)",
                        (scope.conversation, scope.conversation, self.history_turns))

    def shared_summary(self, scope):
        row = self.db.execute("SELECT text,through_id FROM shared_summaries WHERE scope=?",
                              (scope.conversation,)).fetchone()
        return (row[0], row[1]) if row else ("", 0)

    def shared_summary_row(self, scope):
        row = self.db.execute("SELECT * FROM shared_summaries WHERE scope=?",
                              (scope.conversation,)).fetchone()
        return dict(row) if row is not None else None

    def shared_calls_after(self, scope, through, *, limit=None):
        sql = "SELECT * FROM shared_calls WHERE scope=? AND id>? ORDER BY id"
        params = (scope.conversation, through)
        if limit is not None:
            sql += " LIMIT ?"
            params += (limit,)
        return self.db.execute(sql, params).fetchall()

    def pending_shared(self, scope):
        return self.shared_calls_after(scope, self.shared_summary(scope)[1])

    def write_shared_summary(self, scope, name, text, through):
        """Write on the caller's transaction; never commit an enclosing guard."""
        self.db.execute("INSERT OR REPLACE INTO shared_summaries VALUES (?,?,?,?,?,?)",
                        (scope.conversation, scope.realm, str(scope.user_id), name,
                         text[:1500], through))

    def public_candidates(self, user_id: int, guild_id: int | None = None):
        # Server queries include all speakers in this guild. DM queries include only its owner.
        condition, value = (("realm=?", f"guild:{guild_id}") if guild_id is not None
                            else ("user_id=?", str(user_id)))
        rows = self.db.execute(
            "SELECT scope, user_id, MAX(id) AS recent FROM shared_calls WHERE " + condition +
            " GROUP BY scope,user_id ORDER BY recent DESC LIMIT 30", (value,)).fetchall()
        return [Scope(int(r["scope"].split(":")[1]), int(r["scope"].split(":")[3]),
                      int(r["user_id"])) for r in rows]

    def public_context(self, allowed_scopes):
        context = []
        for source in allowed_scopes[:4]:
            rows = self.db.execute("SELECT * FROM shared_calls WHERE scope=? ORDER BY id DESC LIMIT 2",
                                   (source.conversation,)).fetchall()
            context.append({"source": source.conversation, "user_id": str(source.user_id),
                            "name": rows[0]["name"] if rows else "",
                            "summary": self.shared_summary(source)[0],
                            "recent_user_messages": [r["content"] for r in reversed(rows)]})
        return context

